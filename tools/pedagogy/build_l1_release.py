#!/usr/bin/env python3
"""Build the per-scene release list from the owner's direct instruction.

No named reviewer or separate evidence file is required. Scene fingerprints
still prevent carrying an activation instruction onto changed material.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path("docs/integration-ponts-L1/publication-par-langue/statut.json")
BUNDLE = Path("melunga_deploy/content/l1-cafe.json")
OUTPUT = Path("melunga_deploy/l1-cafe-release.js")
PAIRS = ("fr-en", "fr-es", "fr-it", "fr-zh", "fr-ja", "fr-ko", "zh-fr")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def scene_sha256(scene):
    """Hash the entire scene, including exact strings, roles and preparation."""
    raw = json.dumps(scene, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


def release_pairs(manifest, bundle):
    require(isinstance(manifest, dict) and manifest.get("version") == 2
            and manifest.get("activationPolicy") == "owner-instruction-only", "Invalid release manifest")
    require(isinstance(bundle, dict) and bundle.get("version") == 1 and isinstance(bundle.get("pairs"), list), "Invalid scene bundle")
    scenes = bundle["pairs"]
    require(len(scenes) == len(PAIRS) and all(isinstance(p, dict) for p in scenes), "Seven scenes required")
    require([p.get("id") for p in scenes] == list(PAIRS), "Unexpected or duplicate scene pairs")
    rows = manifest.get("pairs")
    require(isinstance(rows, list) and len(rows) == len(PAIRS) and all(isinstance(p, dict) for p in rows), "Seven release records required")
    require([p.get("id") for p in rows] == list(PAIRS), "Unexpected or duplicate release pairs")
    activated = []
    for row, scene in zip(rows, scenes):
        pair = row["id"]
        require(row.get("sceneSha256") == scene_sha256(scene), f"{pair}: scene changed; update its snapshot and owner instruction")
        decision = row.get("kartechApproval")
        require(isinstance(decision, dict) and decision.get("status") in {"pending", "approved", "withheld"}, f"{pair}: invalid owner decision")
        if decision["status"] == "approved":
            require(decision.get("method") == "direct-instruction" and decision.get("actor") == "Kartech", f"{pair}: direct owner instruction required")
            require(decision.get("sceneSha256") == scene_sha256(scene), f"{pair}: owner instruction belongs to another scene version")
            activated.append(pair)
    return activated


def render(pairs):
    data = json.dumps({"version": 1, "pairs": pairs}, ensure_ascii=False, separators=(",", ":"))
    return "/* Generated by tools/pedagogy/build_l1_release.py. Human decisions are separate. */\nwindow.MelungaL1CafeRelease=Object.freeze(" + data + ");\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the delivered list without writing it")
    args = parser.parse_args()
    try:
        manifest = json.loads((ROOT / MANIFEST).read_text())
        bundle = json.loads((ROOT / BUNDLE).read_text())
        pairs = release_pairs(manifest, bundle)
        expected = render(pairs)
        if args.check:
            require((ROOT / OUTPUT).read_text() == expected, "Release script differs from the recorded decisions")
        else:
            (ROOT / OUTPUT).write_text(expected)
        print(json.dumps({"enabledPairs": pairs, "count": len(pairs), "check": args.check}))
    except (ValueError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
