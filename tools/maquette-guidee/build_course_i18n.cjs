#!/usr/bin/env node
'use strict';
// Compile interface translations only. Never reads or rewrites learning cards.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),web=path.join(root,'melunga_deploy');
const directory=path.join(web,'content/course-locales');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const source=read(path.join(__dirname,'course-locale-keys.json'));
const supplements=read(path.join(directory,'supplements.json'));
const codes=['fr','en','es','it','zh','ja','ko','de','ru','pt','ar'];
const sameKeys=(actual,expected,label)=>assert.deepEqual(Object.keys(actual),expected,label+' complete keys');
const tags=s=>(s.match(/<[^>]*>/g)||[]).sort();
const placeholders=s=>(s.match(/\{[a-zA-Z][\w]*\}/g)||[]).sort();
const french={locale:'fr',ui:Object.fromEntries(source.uiKeys.map(k=>[k,k])),
  themes:Object.fromEntries(source.themeKeys.filter(k=>!/[\u3400-\u9fff]/.test(k)).map(k=>[k,k])),
  levels:source.levels,languages:source.languages,formats:source.formats};
const locales={fr:french};
for(const code of codes.filter(c=>c!=='fr')){
  const data=read(path.join(directory,code+'.json'));
  assert.equal(data.locale,code);sameKeys(data,['locale','ui','themes','levels','languages','formats'],code);
  sameKeys(data.ui,source.uiKeys,code+' ui');sameKeys(data.themes,source.themeKeys,code+' themes');
  for(const section of ['levels','languages','formats'])sameKeys(data[section],Object.keys(source[section]),code+' '+section);
  for(const section of ['ui','themes','levels','languages','formats'])for(const [key,value] of Object.entries(data[section])){
    assert.ok(typeof value==='string'&&value.trim(),code+' '+section+' '+key+' is translated');
    const original=section==='ui'||section==='themes'?key:source[section][key];
    assert.deepEqual(tags(value),tags(original),code+' tags '+key);
    assert.deepEqual(placeholders(value),placeholders(original),code+' placeholders '+key);
    if(original.includes('Melunga'))assert.ok(value.includes('Melunga'),code+' brand '+key);
  }
  if(code==='zh')for(const [key,value] of Object.entries(source.chineseLocked))assert.equal(data.ui[key],value,'published Chinese '+key);
  locales[code]=data;
}
for(const code of codes){
  sameKeys(supplements[code],Object.keys(supplements.fr),code+' supplements');
  for(const [key,value] of Object.entries(supplements[code])){
    assert.ok(typeof value==='string'&&value.trim());assert.deepEqual(tags(value),tags(key));assert.deepEqual(placeholders(value),placeholders(key));
    locales[code].ui[key]=value;
  }
}
const output=`/* Generated by tools/maquette-guidee/build_course_i18n.cjs. Interface only. */
(() => {
  'use strict';
  if (window.MelungaCourseI18n) return;
  const dictionaries = ${JSON.stringify(locales)};
  const codes = Object.freeze(${JSON.stringify(codes)});
  function freeze(value) { for (const child of Object.values(value)) if (child && typeof child === 'object') freeze(child); return Object.freeze(value); }
  freeze(dictionaries);
  function dictionary(locale) { if (!codes.includes(locale)) throw new Error('Unsupported interface language'); return dictionaries[locale]; }
  function t(locale, value) { const ui = dictionary(locale).ui; return Object.hasOwn(ui, value) ? ui[value] : value; }
  function theme(locale, title) {
    const values = dictionary(locale).themes;
    if (Object.hasOwn(values, title)) return values[title];
    if (locale === 'fr' && !/[\\u3400-\\u9fff]/.test(title) || locale === 'zh' && /[\\u3400-\\u9fff]/.test(title)) return title;
    throw new Error('Missing theme translation');
  }
  function languageName(locale, code) { const value = dictionary(locale).languages[code]; if (!value) throw new Error('Unsupported study language'); return value; }
  function levelTitle(locale, level) { const value = dictionary(locale).levels[level]; if (!value) throw new Error('Unsupported level'); return value; }
  function format(locale, key, args = {}) {
    const value = dictionary(locale).formats[key]; if (!value) throw new Error('Unsupported interface format');
    return value.replace(/\\{(\\w+)\\}/g, (_, name) => { if (!Object.hasOwn(args, name)) throw new Error('Missing interface format value'); return String(args[name]); });
  }
  Object.defineProperty(window, 'MelungaCourseI18n', {value:Object.freeze({locales:codes,t,theme,languageName,levelTitle,format}),writable:false,configurable:false});
})();
`;
const destination=path.join(web,'course-i18n.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(destination,'utf8'),output,'compiled interface is current');
else fs.writeFileSync(destination,output);
process.stdout.write(JSON.stringify({status:'passed',locales:codes.length,uiKeys:source.uiKeys.length,supplementKeys:Object.keys(supplements.fr).length,themeKeys:source.themeKeys.length,check:process.argv.includes('--check')})+'\n');
