/* Netlify build check. Uses Node built-ins, resolves files from this script,
 * and requires neither Python, Git history nor individual reviewer evidence. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const pairs = ['fr-en','fr-es','fr-it','fr-zh','fr-ja','fr-ko','zh-fr'];
function requireValid(condition, message) { if (!condition) throw new Error(message); }
function object(value) { return value !== null && typeof value === 'object' && !Array.isArray(value); }
function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (object(value)) return '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + canonical(value[key])).join(',') + '}';
  return JSON.stringify(value);
}
function sceneHash(scene) { return crypto.createHash('sha256').update(canonical(scene), 'utf8').digest('hex'); }
function releasePairs(manifest, bundle) {
  requireValid(object(manifest) && manifest.version === 2 && manifest.activationPolicy === 'owner-instruction-only', 'Invalid release manifest');
  requireValid(object(bundle) && bundle.version === 1 && Array.isArray(bundle.pairs), 'Invalid scene bundle');
  const scenes = bundle.pairs, rows = manifest.pairs;
  for (const [items, label] of [[scenes,'scene'],[rows,'release']]) {
    requireValid(Array.isArray(items) && items.length === pairs.length && items.every((row, index) => object(row) && row.id === pairs[index]), 'Unexpected or duplicate ' + label + ' pairs');
  }
  const enabled = [];
  for (let index = 0; index < pairs.length; index++) {
    const row = rows[index], hash = sceneHash(scenes[index]), decision = row.kartechApproval;
    requireValid(row.sceneSha256 === hash, row.id + ': scene changed; update its snapshot and owner instruction');
    requireValid(object(decision) && ['pending','approved','withheld'].includes(decision.status), row.id + ': invalid owner decision');
    if (decision.status === 'approved') {
      requireValid(decision.method === 'direct-instruction' && decision.actor === 'Kartech', row.id + ': direct owner instruction required');
      requireValid(decision.sceneSha256 === hash, row.id + ': owner instruction belongs to another scene version');
      enabled.push(row.id);
    }
  }
  return enabled;
}
function render(enabled) {
  return '/* Generated by tools/pedagogy/build_l1_release.py. Human decisions are separate. */\nwindow.MelungaL1CafeRelease=Object.freeze(' + JSON.stringify({version:1,pairs:enabled}) + ');\n';
}
function check() {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const manifest = JSON.parse(read('docs/integration-ponts-L1/publication-par-langue/statut.json'));
  const bundle = JSON.parse(read('melunga_deploy/content/l1-cafe.json'));
  const enabled = releasePairs(manifest, bundle);
  requireValid(read('melunga_deploy/l1-cafe-release.js') === render(enabled), 'Release script differs from the owner instructions');
  return enabled;
}
module.exports = {sceneHash, releasePairs, render, check};
if (require.main === module) {
  try { const enabled = check(); console.log(JSON.stringify({enabledPairs:enabled,count:enabled.length,check:true})); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
